package secretscan

import "testing"

// Found by the first real sweep (2026-11-22): 5095 clones, and an AWS
// serializer's enc.String("GetSessionToken") was read as a flag.
func TestASerializerCallIsNotAFlag(t *testing.T) {
	src := "package s\nfunc f(enc E, fs F) {\n\tenc.String(\"GetSessionToken\")\n\tfs.String(\"refresh_token\")\n\tfs.StringVar(&x, \"admin-password\", \"\", \"u\")\n\tfs.StringP(\"token\", \"t\", \"\", \"u\")\n}\n"
	gs, err := ScanGo("s.go", []byte(src))
	if err != nil {
		t.Fatal(err)
	}
	var got []string
	for _, f := range gs.Findings {
		got = append(got, f.Name)
	}
	if len(got) != 2 || got[0] != "admin-password" || got[1] != "token" {
		t.Fatalf("findings %v, want the two real flags", got)
	}
}

func TestGeneratedCodeIsASchemaNotAConfiguration(t *testing.T) {
	src := "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage api\n\ntype Req struct {\n\tPassword string `json:\"password\"`\n}\n"
	gs, err := ScanGo("api.pb.go", []byte(src))
	if err != nil || len(gs.Findings) != 0 {
		t.Fatalf("%+v %v", gs, err)
	}
}

func TestAgentWorktreesAndNestedModuleCachesAreNotScanned(t *testing.T) {
	const unit = "[Service]\nExecStart=/bin/x --token abc123\n"
	root := tree(t, map[string]string{
		"deploy/a.service":                         unit,
		".claude/worktrees/w/deploy/b.service":     unit,
		"homes/h/go/pkg/mod/m@v1/deploy/c.service": unit,
	})
	r, err := ScanRepo(root, false)
	if err != nil {
		t.Fatal(err)
	}
	if n := len(r.Plaintext()); n != 1 {
		t.Fatalf("%d plaintext inputs, want only deploy/a.service: %+v", n, r.Findings)
	}
}
